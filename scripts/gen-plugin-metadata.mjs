/**
 * Lightweight script that writes packages/web/src/lib/plugin-downloads.generated.ts
 * using the current root package.json version — WITHOUT building any extensions.
 *
 * Used as the `predev` hook so `npm run dev` works immediately after checkout.
 * The full `package-plugins.mjs` script (used in `prebuild`) also calls this
 * after actually building the extension artifacts.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const rootDir = resolve(scriptDir, '..');
const packageJsonPath = join(rootDir, 'package.json');
const { version } = JSON.parse(readFileSync(packageJsonPath, 'utf8'));

const generatedMetadataPath = join(
  rootDir,
  'packages',
  'web',
  'src',
  'lib',
  'plugin-downloads.generated.ts',
);

const fileContents = `// Generated by scripts/gen-plugin-metadata.mjs. Do not edit manually.
export const pluginArtifactVersion = ${JSON.stringify(version)} as const;

export const pluginArtifacts = {
  chromium: ${JSON.stringify(`/downloads/inbox-rs-chromium-${version}.zip`)},
  firefox: ${JSON.stringify(`/downloads/inbox-rs-firefox-${version}.xpi`)},
  thunderbird: ${JSON.stringify(`/downloads/inbox-rs-thunderbird-${version}.xpi`)},
} as const;
`;

let existingContents = null;
try {
  existingContents = readFileSync(generatedMetadataPath, 'utf8');
} catch {
  existingContents = null;
}

if (existingContents !== fileContents) {
  writeFileSync(generatedMetadataPath, fileContents);
  console.log(`[gen-plugin-metadata] wrote ${generatedMetadataPath}`);
} else {
  console.log(`[gen-plugin-metadata] up to date, no changes written`);
}

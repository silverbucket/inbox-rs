/**
 * Lightweight script that writes packages/web/src/lib/plugin-downloads.generated.ts
 * using the current per-package versions — WITHOUT building any extensions.
 *
 * The web app's footer version comes from the root package.json (the *web* app
 * release). The download links and per-artifact version labels come from
 * each extension's own package.json so they reflect the actual built bundle
 * (which may lag the web release if no extension code changed since the
 * previous tag — see scripts/release-bump.mjs).
 *
 * Used as the `predev` hook so `npm run dev` works immediately after checkout.
 * The full `package-plugins.mjs` script (used in `prebuild`) also calls this
 * after actually building the extension artifacts.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const rootDir = resolve(scriptDir, '..');

/** Read the `version` field from a `package.json` at the given path. */
export function readPackageVersion(pkgJsonPath) {
  return JSON.parse(readFileSync(pkgJsonPath, 'utf8')).version;
}

/**
 * Build the contents of `plugin-downloads.generated.ts`.
 *
 * Pure function — no filesystem access — so it can be unit-tested directly
 * with fixture inputs.
 */
export function buildMetadataContents({
  webVersion,
  extensionVersion,
  thunderbirdVersion,
}) {
  const chromiumPath = `/downloads/inbox-rs-chromium-${extensionVersion}.zip`;
  const firefoxPath = `/downloads/inbox-rs-firefox-${extensionVersion}.xpi`;
  const thunderbirdPath = `/downloads/inbox-rs-thunderbird-${thunderbirdVersion}.xpi`;

  return `// Generated by scripts/gen-plugin-metadata.mjs. Do not edit manually.
//
// appVersion is the web app's release version (root package.json).
// Each entry in pluginArtifacts carries its own version because extensions
// only re-version when their bundle actually changes — see
// scripts/release-bump.mjs.
export const appVersion = ${JSON.stringify(webVersion)} as const;

export const pluginArtifacts = {
  chromium: {
    url: ${JSON.stringify(chromiumPath)},
    version: ${JSON.stringify(extensionVersion)},
  },
  firefox: {
    url: ${JSON.stringify(firefoxPath)},
    version: ${JSON.stringify(extensionVersion)},
  },
  thunderbird: {
    url: ${JSON.stringify(thunderbirdPath)},
    version: ${JSON.stringify(thunderbirdVersion)},
  },
} as const;

export type PluginArtifactKey = keyof typeof pluginArtifacts;
`;
}

/** CLI entrypoint — read the per-package versions from disk and write the file. */
export function main() {
  const generatedMetadataPath = join(
    rootDir,
    'packages',
    'web',
    'src',
    'lib',
    'plugin-downloads.generated.ts',
  );

  const contents = buildMetadataContents({
    webVersion: readPackageVersion(join(rootDir, 'package.json')),
    extensionVersion: readPackageVersion(
      join(rootDir, 'packages', 'extension', 'package.json'),
    ),
    thunderbirdVersion: readPackageVersion(
      join(rootDir, 'packages', 'thunderbird', 'package.json'),
    ),
  });

  let existingContents = null;
  try {
    existingContents = readFileSync(generatedMetadataPath, 'utf8');
  } catch {
    existingContents = null;
  }

  if (existingContents !== contents) {
    writeFileSync(generatedMetadataPath, contents);
    console.log(`[gen-plugin-metadata] wrote ${generatedMetadataPath}`);
  } else {
    console.log(`[gen-plugin-metadata] up to date, no changes written`);
  }
}

// Run main() only when invoked as a script, not when imported by tests.
if (import.meta.url === `file://${process.argv[1]}`) {
  main();
}
